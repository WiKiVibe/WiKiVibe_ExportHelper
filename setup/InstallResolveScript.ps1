# Install Resolve Workspace > Scripts entry only
param([switch]$Silent)

$ErrorActionPreference = "Stop"
$BrandName = "WiKiVibe"
$ProductName = "ExportHelper"
$AppName = "$BrandName $ProductName"
$ResolveScriptName = "${BrandName}_${ProductName}"
$SetupDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$SourceRoot = Split-Path -Parent $SetupDir
$InstallRoot = Join-Path $env:LOCALAPPDATA "$BrandName\$ProductName"
$ResolveMenuRoot = Join-Path $env:APPDATA "Blackmagic Design\DaVinci Resolve\Support\Fusion\Scripts\Utility"

function Find-Python {
    $candidates = @(
        (Join-Path $env:LOCALAPPDATA "Programs\Python\Python313\python.exe"),
        (Join-Path $env:LOCALAPPDATA "Programs\Python\Python312\python.exe"),
        (Join-Path $env:LOCALAPPDATA "Programs\Python\Python311\python.exe"),
        (Join-Path $env:LOCALAPPDATA "Programs\Python\Python310\python.exe")
    )
    foreach ($p in $candidates) {
        if (Test-Path -LiteralPath $p) { return $p }
    }
    try {
        $py = & py -3 -c "import sys; print(sys.executable)" 2>$null
        if ($LASTEXITCODE -eq 0 -and $py) {
            $py = $py.Trim()
            if (Test-Path -LiteralPath $py) { return $py }
        }
    } catch {}
    return $null
}

function Show-Msg([string]$Text) {
    if ($Silent) { Write-Host $Text; return }
    Add-Type -AssemblyName PresentationFramework | Out-Null
    [System.Windows.MessageBox]::Show($Text, $AppName) | Out-Null
}

if (-not (Test-Path -LiteralPath (Join-Path $InstallRoot "export_helper.py"))) {
    $fallback = Join-Path $SourceRoot "app\export_helper.py"
    if (Test-Path -LiteralPath $fallback) {
        $InstallRoot = Join-Path $SourceRoot "app"
    }
}
if (-not (Test-Path -LiteralPath (Join-Path $InstallRoot "export_helper.py"))) {
    Show-Msg "export_helper.py not found. Run START_HERE.bat first.`n`n找不到主程式，請先執行 START_HERE.bat。"
    exit 2
}

$python = Find-Python
if ($python) {
    $pythonw = Join-Path (Split-Path $python) "pythonw.exe"
    if (-not (Test-Path -LiteralPath $pythonw)) { $pythonw = $python }
} else {
    $pythonw = "pythonw"
}

New-Item -ItemType Directory -Force -Path $ResolveMenuRoot | Out-Null
$menuScript = Join-Path $ResolveMenuRoot ($ResolveScriptName + ".py")
$menuLines = @(
    "# Auto-generated by $AppName.",
    "import subprocess",
    "from pathlib import Path",
    "",
    "HELPER = Path(r'$InstallRoot') / 'export_helper.py'",
    "PYTHONW = Path(r'$pythonw')",
    "CWD = Path(r'$InstallRoot')",
    "",
    "def main():",
    "    if not HELPER.is_file():",
    "        raise SystemExit(f'ExportHelper not found: {HELPER}')",
    "    exe = str(PYTHONW if PYTHONW.is_file() else 'python')",
    "    subprocess.Popen([exe, str(HELPER)], cwd=str(CWD))",
    "",
    "if __name__ == '__main__':",
    "    main()",
    ""
)
Set-Content -LiteralPath $menuScript -Value $menuLines -Encoding UTF8

$legacyScripts = @(
    "WiKiVibe_DRT_Timeline_Export.py",
    "WiKiVibe_ResolveTimelinePackager.py",
    "ResolveTimelinePackager.py"
)
$removed = @()
foreach ($legacy in $legacyScripts) {
    $legacyPath = Join-Path $ResolveMenuRoot $legacy
    if (Test-Path -LiteralPath $legacyPath) {
        Remove-Item -LiteralPath $legacyPath -Force
        $removed += $legacy
    }
}

$removedText = if ($removed.Count -gt 0) {
    "Removed old scripts:`n- " + ($removed -join "`n- ")
} else {
    "No legacy scripts found."
}

Show-Msg @"
Resolve script installed / 已安裝 Resolve 選單腳本

Menu name:
Workspace > Scripts > $ResolveScriptName

$menuScript

$removedText

Restart DaVinci Resolve for the menu to refresh.
請重新啟動 Resolve 後再從 Workspace > Scripts 開啟。
"@
exit 0
